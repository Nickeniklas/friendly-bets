// One-off / re-runnable helper: downloads the 32 NHL team logos (light + dark
// SVGs from assets.nhle.com) into public/teams/nhl/ and regenerates
// src/lib/team-logos-nhl.ts, so the app serves them as static assets instead of
// hotlinking the NHL's CDN. The Liiga equivalent is scripts/copy-team-logos.mjs.
//
// Run with: node scripts/copy-nhl-logos.mjs
// Re-run when the team set changes (relocation / expansion / rebrand) or the
// season moves on. It is NOT part of the build or /api/sync — commit the
// downloaded SVGs and the regenerated map.

import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

// Same endpoint as src/lib/nhl.ts. Walk forward a week at a time from the
// season start until every team has appeared at least once.
const NHL_SCHEDULE_URL = "https://api-web.nhle.com/v1/schedule";
const SEASON_START = "2026-09-29"; // regularSeasonStartDate
const TEAM_COUNT = 32;
const MAX_WEEKS = 8;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const destDir = path.join(root, "public", "teams", "nhl");
const mapFile = path.join(root, "src", "lib", "team-logos-nhl.ts");

/** Downloads an SVG to public/teams/nhl/<file>; returns the public path. */
async function download(url, file) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status} ${res.statusText}`);
  const type = (res.headers.get("content-type") ?? "").split(";")[0].trim();
  if (type !== "image/svg+xml") throw new Error(`${url}: unexpected content-type "${type}"`);
  const svg = await res.text();
  // These are served as <img> (scripts never run there), but don't commit
  // anything that looks active anyway.
  if (/<script|\bon\w+\s*=/i.test(svg)) throw new Error(`${url}: SVG contains script/handlers`);
  await writeFile(path.join(destDir, file), svg);
  return `/teams/nhl/${file}`;
}

// Team name (commonName.default, the string stored in matches.team1/team2) → team.
const teams = new Map();
const date = new Date(`${SEASON_START}T00:00:00Z`);
for (let week = 0; week < MAX_WEEKS && teams.size < TEAM_COUNT; week++) {
  const day = date.toISOString().slice(0, 10);
  const res = await fetch(`${NHL_SCHEDULE_URL}/${day}`);
  if (!res.ok) throw new Error(`Failed to fetch schedule ${day}: ${res.status} ${res.statusText}`);
  const data = await res.json();
  for (const game of (data.gameWeek ?? []).flatMap((d) => d.games ?? [])) {
    if (game.gameType !== 2) continue; // regular season only
    for (const team of [game.homeTeam, game.awayTeam]) {
      const name = team?.commonName?.default;
      if (name && team.logo && team.darkLogo && !teams.has(name)) teams.set(name, team);
    }
  }
  date.setUTCDate(date.getUTCDate() + 7);
}
if (teams.size !== TEAM_COUNT) {
  throw new Error(`Expected ${TEAM_COUNT} teams, found ${teams.size}: ${[...teams.keys()].join(", ")}`);
}

await mkdir(destDir, { recursive: true });

const entries = [];
for (const [name, team] of [...teams].sort(([a], [b]) => a.localeCompare(b, "en"))) {
  const slug = team.abbrev.toLowerCase(); // "TOR" → tor.svg / tor-dark.svg
  const light = await download(team.logo, `${slug}.svg`);
  const dark = await download(team.darkLogo, `${slug}-dark.svg`);
  entries.push({ name, light, dark });
  console.log(`  ${name.padEnd(14)} ${light}  + ${dark}`);
}

const lines = entries.map(
  ({ name, light, dark }) =>
    `  ${JSON.stringify(name)}: { light: ${JSON.stringify(light)}, dark: ${JSON.stringify(dark)} },`
);

await writeFile(
  mapFile,
  `// GENERATED by scripts/copy-nhl-logos.mjs — re-run it instead of editing by hand.
/**
 * NHL team names (exactly as stored in \`matches.team1\` / \`matches.team2\`,
 * i.e. the schedule API's \`commonName.default\`) → their logo SVGs in
 * public/teams/nhl/. Every team has a dark-background variant (the NHL's
 * \`darkLogo\`), used in dark mode instead of the light-circle backing. Looked
 * up per competition via teamLogo() in src/lib/team-logos.ts.
 */
import type { TeamLogo } from "./team-logos";

export const NHL_TEAM_LOGOS: Record<string, TeamLogo> = {
${lines.join("\n")}
};
`
);

console.log(`Downloaded ${entries.length} NHL team logos (light + dark) to public/teams/nhl/ and wrote src/lib/team-logos-nhl.ts`);
