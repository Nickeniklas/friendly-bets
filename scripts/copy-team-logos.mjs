// One-off / re-runnable helper: downloads the Liiga team logos into
// public/teams/ and regenerates src/lib/team-logos.ts, so the app serves them
// as static assets instead of hotlinking liiga.fi's CMS (cdn.builder.io asset
// URLs can change at any time). Same idea as scripts/copy-flags.mjs.
//
// Run with: node scripts/copy-team-logos.mjs
// Re-run when the team set changes (e.g. a team is promoted), or when the
// season in LIIGA_GAMES_URL moves on. It is NOT part of the build or /api/sync
// — commit the downloaded images and the regenerated map.

import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

// Keep in sync with LIIGA_GAMES_URL in src/lib/liiga.ts.
const LIIGA_GAMES_URL =
  "https://liiga.fi/api/v2/games?tournament=runkosarja&season=2027";

const EXTENSIONS = {
  "image/png": "png",
  "image/svg+xml": "svg",
  "image/webp": "webp",
  "image/jpeg": "jpg",
};

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const destDir = path.join(root, "public", "teams");
const mapFile = path.join(root, "src", "lib", "team-logos.ts");

/** "Kärpät" -> "karpat", "K-Espoo" -> "k-espoo". */
function slugify(name) {
  return name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** Downloads `url` to public/teams/<basename>.<ext>; returns the public path. */
async function download(url, basename) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status} ${res.statusText}`);
  const type = (res.headers.get("content-type") ?? "").split(";")[0].trim();
  const ext = EXTENSIONS[type];
  if (!ext) throw new Error(`${url}: unexpected content-type "${type}"`);
  const file = `${basename}.${ext}`;
  await writeFile(path.join(destDir, file), Buffer.from(await res.arrayBuffer()));
  return `/teams/${file}`;
}

const res = await fetch(LIIGA_GAMES_URL);
if (!res.ok) throw new Error(`Failed to fetch games: ${res.status} ${res.statusText}`);
const games = await res.json();

// Unique teams by name (the same string stored in matches.team1/team2).
const logosByTeam = new Map();
for (const game of games) {
  for (const team of [game.homeTeam, game.awayTeam]) {
    if (team?.teamName && team.logos?.lightBg && !logosByTeam.has(team.teamName)) {
      logosByTeam.set(team.teamName, team.logos);
    }
  }
}

await mkdir(destDir, { recursive: true });

const entries = [];
for (const [teamName, logos] of [...logosByTeam].sort(([a], [b]) => a.localeCompare(b, "fi"))) {
  const slug = slugify(teamName);
  const light = await download(logos.lightBg, slug);
  // Only fetch a dark variant when liiga.fi actually has a different one.
  const dark =
    logos.darkBg && logos.darkBg !== logos.lightBg
      ? await download(logos.darkBg, `${slug}-dark`)
      : undefined;
  entries.push({ teamName, light, dark });
  console.log(`  ${teamName.padEnd(10)} ${light}${dark ? `  + ${dark}` : ""}`);
}

const lines = entries.map(
  ({ teamName, light, dark }) =>
    `  ${JSON.stringify(teamName)}: { light: ${JSON.stringify(light)}${
      dark ? `, dark: ${JSON.stringify(dark)}` : ""
    } },`
);

await writeFile(
  mapFile,
  `// GENERATED by scripts/copy-team-logos.mjs — re-run it instead of editing by hand.
/**
 * Maps team names (exactly as stored in \`matches.team1\` / \`matches.team2\`,
 * i.e. liiga.fi's \`teamName\`) to their logo files in public/teams/.
 * \`dark\` exists only when liiga.fi has a separate dark-background variant;
 * otherwise \`light\` is used in both themes. \`Flag\` (src/components/flag.tsx)
 * falls back to these when a team has no country flag.
 */
export type TeamLogo = { light: string; dark?: string };

export const TEAM_LOGOS: Record<string, TeamLogo> = {
${lines.join("\n")}
};
`
);

const darkCount = entries.filter((e) => e.dark).length;
console.log(
  `Downloaded ${entries.length} team logos (+${darkCount} dark variants) to public/teams/ and wrote src/lib/team-logos.ts`
);
